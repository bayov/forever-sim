package paladin

import (
	"github.com/wowsims/classic/sim/core"
)

// RighteousFuryAllThreat is the 33% all threat of the 2026-10-30 hotfix.
const RighteousFuryAllThreat = 1.33

func (paladin *Paladin) registerRighteousFury() {
	// Righteous Fury is on or off for the whole fight. Instrument of Law's threat cut while it was
	// off left the tree with the October 30 hotfix.
	if !paladin.Options.RighteousFury {
		return
	}
	actionID := core.ActionID{SpellID: 25780}

	// Forever's Righteous Fury is 90% Holy threat again in client 70425 (spell 25780), after 60%
	// in 70338. Improved Righteous Fury takes 3% a rank off all damage taken since the October 30
	// hotfix (spell 20468's trait ranks in 1.60.1.70707+hf, 3 / 6 / 9%; 2% a rank before).
	//
	// The launch realms' hotfix to the October 30 build (foreverchanges.pro/patch-notes, not in
	// Blizzard's notes) adds 33% to all threat: "Increases all threat generated by 33%, and all
	// threat generated by your Holy attacks by an additional 90%." Under Forever each percent
	// row is its own factor, so Holy threat is 1.33 * 1.9.
	rfThreatMultiplier := 1.9
	paladin.PseudoStats.ThreatMultiplier *= RighteousFuryAllThreat
	damageTaken := 1 - 0.03*float64(paladin.Talents.ImprovedRighteousFury)

	paladin.OnSpellRegistered(func(spell *core.Spell) {
		if spell.SpellSchool.Matches(core.SpellSchoolHoly) {
			spell.ThreatMultiplier *= rfThreatMultiplier
		}
	})

	rfAura := core.MakePermanent(&core.Aura{Label: "Righteous Fury", ActionID: actionID})
	paladin.RegisterAura(*rfAura)
	paladin.PseudoStats.DamageTakenMultiplier *= damageTaken
}

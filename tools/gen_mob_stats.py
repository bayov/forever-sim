#!/usr/bin/python

# Generates sim/core/mob_stats_auto_gen.go: what an average normal mob looks like at each
# level from 1 to 60, for the leveling sim (docs/leveling_sim.md).
#
# It reads assets/db_inputs/mobs/normal_mobs.csv (tools/export_normal_mobs.py) and averages
# the melee mobs at each level, each one weighted by its spawn count. Casters (mage class
# mobs, 3% of the spawns) are left out. Warrior class mobs are 85% of the spawns and
# paladin class ones 12%: melee mobs with about 80% of the armor and health, which stay in.
#
# A mob that spans several levels counts at each of them with its spawns split evenly, and
# its health goes linearly from its lowest level to its highest. Its melee damage takes its
# attack power the way the 1.12 servers did: AP / 14 per second of swing time.
#
#   python3 tools/gen_mob_stats.py

import csv

IN = "assets/db_inputs/mobs/normal_mobs.csv"
OUT = "sim/core/mob_stats_auto_gen.go"

MELEE_CLASSES = {"1", "2", "4"}
# The 1.12 creature types as proto.MobType.
MOB_TYPES = {
    "1": "MobTypeBeast", "2": "MobTypeDragonkin", "3": "MobTypeDemon", "4": "MobTypeElemental", "5": "MobTypeGiant",
    "6": "MobTypeUndead", "7": "MobTypeHumanoid", "9": "MobTypeMechanical", "10": "MobTypeUnknown",
}
TYPE_ORDER = ["MobTypeBeast", "MobTypeHumanoid", "MobTypeUndead", "MobTypeElemental", "MobTypeDemon",
              "MobTypeDragonkin", "MobTypeGiant", "MobTypeMechanical", "MobTypeUnknown"]
# A run speed of 1.0 is 7 yards a second.
RUN_SPEED_YARDS = 7.0

levels = {level: [] for level in range(1, 61)}
with open(IN) as f:
    for r in csv.DictReader(f):
        if r["unit_class"] not in MELEE_CLASSES:
            continue
        lo, hi = int(r["min_level"]), int(r["max_level"])
        speed = float(r["melee_base_attack_time"]) / 1000
        ap_damage = float(r["melee_attack_power"]) / 14 * speed
        mob = {
            "armor": float(r["armor"]),
            "min_dps": (float(r["min_melee_dmg"]) + ap_damage) / speed,
            "max_dps": (float(r["max_melee_dmg"]) + ap_damage) / speed,
            "speed": speed,
            "run": float(r["speed_run"]) * RUN_SPEED_YARDS,
            "type": MOB_TYPES[r["creature_type"]],
        }
        for level in range(lo, hi + 1):
            t = 0 if hi == lo else (level - lo) / (hi - lo)
            health = float(r["min_level_health"]) + (float(r["max_level_health"]) - float(r["min_level_health"])) * t
            levels[level].append((int(r["spawns"]) / (hi - lo + 1), dict(mob, health=health)))


def mean(mobs, key):
    return sum(w * m[key] for w, m in mobs) / sum(w for w, _ in mobs)


lines = []
for level in range(1, 61):
    mobs = levels[level]
    total = sum(w for w, _ in mobs)
    speed = mean(mobs, "speed")
    # Damage a swing at the average swing time, so that it keeps the average mob's damage a
    # second.
    min_damage = mean(mobs, "min_dps") * speed
    max_damage = mean(mobs, "max_dps") * speed
    types = {t: 0.0 for t in TYPE_ORDER}
    for w, m in mobs:
        types[m["type"]] += w / total
    mix = ", ".join(f"proto.MobType_{t}: {share:.3f}" for t, share in types.items() if share >= 0.0005)
    lines.append(
        f"\t{{Level: {level}, Health: {mean(mobs, 'health'):.0f}, Armor: {mean(mobs, 'armor'):.0f}, "
        f"MinDamage: {min_damage:.1f}, MaxDamage: {max_damage:.1f}, SwingSpeed: {speed:.2f}, "
        f"RunSpeed: {mean(mobs, 'run'):.2f}, Spawns: {total:.0f},\n\t\tMobTypes: map[proto.MobType]float64{{{mix}}}}},")

with open(OUT, "w") as f:
    f.write("""package core

// **************************************
// AUTO GENERATED BY GEN_MOB_STATS.PY
// **************************************

import "github.com/wowsims/classic/sim/core/proto"

// The average normal melee mob at each level, index 0 is level 1, from the 1.12 world
// database weighted by spawns (tools/gen_mob_stats.py).
var normalMobStatsByLevel = [60]NormalMobStats{
""")
    f.write("\n".join(lines))
    f.write("\n}\n")
print(f"wrote {OUT}")

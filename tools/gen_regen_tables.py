#!/usr/bin/python

# Generates sim/core/regen_tables_auto_gen.go: the out of combat health regen ratios per Spirit
# by class and level, levels 1-60.
#
# WoW: Forever's regen from Spirit has the shape of Wrath's game tables, not 1.12's formulas:
# mana regen a second is 0.25 per Spirit for the first 50 and less past that (notes.md, Need to
# Verify), and a player's measured health ticks are Spirit times a class and level ratio, with
# a lower ratio past 50 Spirit and no constant (eu.forums.blizzard.com/en/wow/t/635182). The
# Forever client has no regen tables (the server holds them), so we take Wrath's from the
# Titan client (wago.tools, build 3.80.2.70315, gametables/octregenhp.txt for the first 50
# Spirit and gametables/regenhpperspt.txt past that; the 3.3.5 server's are the same). They
# give health a 2 sec tick.
#
#   python3 tools/gen_regen_tables.py

DIR = "assets/db_inputs/basestats/"
OUT = "sim/core/regen_tables_auto_gen.go"

CLASSES = ["Warrior", "Paladin", "Hunter", "Rogue", "Priest", "Shaman", "Mage", "Warlock", "Druid"]


def read_gt(name):
    lines = open(DIR + name).read().splitlines()
    header = lines[0].split("\t")
    rows = {}
    for line in lines[1:]:
        parts = line.split("\t")
        if len(parts) == len(header):
            rows[int(parts[0])] = dict(zip(header[1:], map(float, parts[1:])))
    return rows


base = read_gt("octregenhp.txt")
more = read_gt("regenhpperspt.txt")

out = [
    "// Code generated by tools/gen_regen_tables.py. DO NOT EDIT.",
    "",
    "package core",
    "",
    'import "github.com/wowsims/classic/sim/core/proto"',
    "",
    "// healthRegenPerSpirit is the health a 2 sec tick out of combat for each of the first 50",
    "// Spirit and for each past that, by class and level (index level - 1).",
    "var healthRegenPerSpirit = map[proto.Class][60][2]float64{",
]
for cls in CLASSES:
    out.append(f"\tproto.Class_Class{cls}: {{")
    for level in range(1, 61):
        out.append(f"\t\t{{{base[level][cls]:.6f}, {more[level][cls]:.6f}}},")
    out.append("\t},")
out.append("}")
open(OUT, "w").write("\n".join(out) + "\n")

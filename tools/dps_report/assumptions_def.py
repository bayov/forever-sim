"""assumptions_def.py: the dashboard's assumption scenarios (orchestration/spec_assumptions.md plus later additions).

Each assumption is written for a player who hasn't read our notes:
- label: a plain question or statement, 8 words at most (the panel's row title);
- short: one sentence of about 12 words, what's unknown, in game terms (under the title);
- desc: 1 or 2 short sentences for the Method tab, only what the label and short don't say; src: a terse reference
  (a muted footnote there);
- builds: the request ids it touches; default: the setting the presets use; expected: our best guess for release;
- settings: (id, label, value, rationale, env, edit). The label says what the choice means ("Flat (level 30 value)"),
  the value gives the numbers, the rationale (a few words) why it's a candidate. env is the DASH_ASSUME pairs the
  knob reads, edit names a request edit run_assumptions.py applies. The page tags each setting Low / Expected / High
  from its id.
- warn (optional): {build: note}, a warning icon with that note on the build's non-default cells.
status 'pending' = listed but not simulated yet; 'inert' = no longer applies.
"""

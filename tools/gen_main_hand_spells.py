#!/usr/bin/env python3
"""Write sim/core/client_main_hand_spells_auto_gen.go from the client's SpellMisc table.

    python3 tools/gen_main_hand_spells.py [build]
    gofmt -w sim/core/client_main_hand_spells_auto_gen.go

The build defaults to the newest cached one, with the server's hotfix rows (+hf) when we
have them.

It lists every spell whose SpellMisc row has Attributes_3 0x400 (requires a main hand
weapon) or Attributes_0 0x4 (on next swing). Under Forever these are the melee abilities
that roll Windfury Totem, besides white main hand swings (the user's log audit in
tools/logcheck/findings.md, standards.md rule 17). The sim reads the list through
core.ClientMainHandSpell.
"""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), 'sources'))
import wago  # noqa: E402

ATTR0_ON_NEXT_SWING = 0x4
ATTR3_MAIN_HAND = 0x400
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'sim', 'core',
                   'client_main_hand_spells_auto_gen.go')


def main():
    if len(sys.argv) > 1:
        v = wago.version(sys.argv[1])
    else:
        v = wago.cached()[-1]
        if os.path.isdir(os.path.join(wago.CACHE, v + '+hf')):
            v += '+hf'
    names = {r['ID']: r['Name_lang'] for r in wago.rows('SpellName', v)}
    spells = {}
    for r in wago.rows('SpellMisc', v):
        a0, a3 = int(r['Attributes_0']), int(r['Attributes_3'])
        why = []
        if a0 & ATTR0_ON_NEXT_SWING:
            why.append('on next swing')
        if a3 & ATTR3_MAIN_HAND:
            why.append('main hand')
        if why:
            spells[int(r['SpellID'])] = '%s (%s)' % (names.get(r['SpellID'], '?'), ', '.join(why))
    out = ['// Code generated by tools/gen_main_hand_spells.py from client %s SpellMisc. DO NOT EDIT.\n' % v,
           '\npackage core\n',
           '\n// clientMainHandSpells holds every spell whose client SpellMisc row has Attributes_3 0x400\n',
           '// (requires a main hand weapon) or Attributes_0 0x4 (on next swing).\n',
           'var clientMainHandSpells = map[int32]bool{\n']
    for sid in sorted(spells):
        out.append('\t%d: true, // %s\n' % (sid, spells[sid]))
    out.append('}\n')
    with open(OUT, 'w') as f:
        f.write(''.join(out))
    print('%d spells from %s' % (len(spells), v))


if __name__ == '__main__':
    main()

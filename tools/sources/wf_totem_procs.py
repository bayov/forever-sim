#!/usr/bin/env python3
"""Write sim/core/windfury_totem_procs_forever.go from the Forever client's SpellMisc table.

Windfury Totem rolls on white main hand swings and on the melee abilities whose spell needs a
main hand weapon (Attributes_3 0x400) or comes on the next swing (Attributes_0 0x4). Our live
logs of 2026-11-06 to 11 fit that rule on every ability with enough data (log audit 2026-11-12).

Usage: tools/sources/wf_totem_procs.py [wago build folder]
The folder defaults to the newest one in ~/forever-logs/wago.
"""
import csv
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
OUT = os.path.join(ROOT, "sim/core/windfury_totem_procs_forever.go")


def main():
    base = os.path.expanduser("~/forever-logs/wago")
    folder = sys.argv[1] if len(sys.argv) > 1 else os.path.join(base, sorted(os.listdir(base))[-1])
    build = os.path.basename(folder.rstrip("/"))
    ids = set()
    with open(os.path.join(folder, "SpellMisc.csv")) as f:
        for row in csv.DictReader(f):
            if int(row["Attributes_3"]) & 0x400 or int(row["Attributes_0"]) & 0x4:
                ids.add(int(row["SpellID"]))

    lines, cur = [], ""
    for spell_id in sorted(ids):
        item = f"{spell_id}: true, "
        if len(cur) + len(item) > 96:
            lines.append(cur.rstrip())
            cur = ""
        cur += item
    lines.append(cur.rstrip())

    with open(OUT, "w") as f:
        f.write(f"""// Code generated by tools/sources/wf_totem_procs.py from client {build}. DO NOT EDIT.

package core

// windfuryTotemAbilityIds are the spells that roll Windfury Totem under Forever, besides white
// main hand swings: those that need a main hand weapon (SpellMisc Attributes_3 0x400) or come on
// the next swing (Attributes_0 0x4).
var windfuryTotemAbilityIds = map[int32]bool{{
""")
        for line in lines:
            f.write("\t" + line + "\n")
        f.write("}\n")
    print(f"{len(ids)} spells from {build} -> {os.path.relpath(OUT, ROOT)}")


if __name__ == "__main__":
    main()
